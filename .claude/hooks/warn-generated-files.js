#!/usr/bin/env node
/**
 * PreToolUse(Edit|Write) reminder — generated / seed-then-verified files.
 *
 * These files are produced by a script (or seeded then hand-verified), so hand-editing them drifts
 * from their source of truth. This surfaces an "ask" so an intentional edit (e.g. hand-verifying the
 * mechanic-drops seed — the one legitimate case) still proceeds after a confirm, while an accidental
 * hand-edit gets a nudge to re-run the owning script instead.
 *
 * Fails open (exit 0) on any parse error.
 */
const GENERATED = {
  'docs/api-endpoints.md': 'npx electron scripts/discover-api.js (ELECTRON_RUN_AS_NODE unset)',
  'lib/categories.js': 'npm run generate-categories (ELECTRON_RUN_AS_NODE unset)',
  'data/item-descriptions.json': 'npx electron scripts/discover-currency-descriptions.js',
  'data/mechanic-drops.json': 'npx electron scripts/discover-mechanic-drops.js, then hand-verify',
};

let raw = '';
process.stdin.on('data', (c) => (raw += c));
process.stdin.on('end', () => {
  let fp = '';
  try {
    fp = (JSON.parse(raw).tool_input || {}).file_path || '';
  } catch {
    process.exit(0);
  }
  const norm = fp.replace(/\\/g, '/');
  const hit = Object.keys(GENERATED).find((g) => norm.endsWith(g));
  if (hit) {
    console.log(
      JSON.stringify({
        hookSpecificOutput: {
          hookEventName: 'PreToolUse',
          permissionDecision: 'ask',
          permissionDecisionReason: `${hit} is generated by: ${GENERATED[hit]}. Prefer re-running that over hand-editing (verifying the mechanic-drops seed is the intended exception). Proceed with a manual edit?`,
        },
      })
    );
  }
  process.exit(0);
});
